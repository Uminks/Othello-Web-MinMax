export function createTranslator(language) {
  return (key, values = {}) => {
    const template = translations[language]?.[key] ?? translations.es[key] ?? key;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template,
    );
  };
}
